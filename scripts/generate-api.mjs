import { readFile, writeFile } from 'node:fs/promises';

// Deliberately small generator for the checked-in Spring OpenAPI schema subset.
// Fail on unsupported constructs instead of silently producing an untyped client.
const spec = JSON.parse(await readFile('docs/api/openapi.json', 'utf8'));
function type(s = {}) {
  if (s.$ref) return s.$ref.split('/').at(-1);
  if (s.enum) return s.enum.map(x => JSON.stringify(x)).join(' | ');
  if (s.oneOf || s.anyOf) return (s.oneOf || s.anyOf).map(type).join(' | ');
  if (s.allOf) return s.allOf.map(type).join(' & ');
  if (s.type === 'array') return `Array<${type(s.items)}>`;
  if (s.type === 'object' || s.properties) {
    const props = Object.entries(s.properties || {}).map(([k, v]) => `${JSON.stringify(k)}${(s.required || []).includes(k) ? '' : '?'}: ${type(v)}`).join('; ');
    return s.additionalProperties ? `Record<string, ${s.additionalProperties === true ? 'unknown' : type(s.additionalProperties)}>` : `{ ${props} }`;
  }
  if (s.type === 'integer' || s.type === 'number') return 'number';
  if (s.type === 'string' || s.type === 'boolean') return s.type;
  if (Object.keys(s).length === 0) return 'unknown';
  throw new Error(`Unsupported schema: ${JSON.stringify(s)}`);
}
const content = value => Object.values(value?.content || {})[0]?.schema;
let out = '// Generated by scripts/generate-api.mjs from docs/api/openapi.json. Do not edit.\n';
for (const [name, schema] of Object.entries(spec.components.schemas)) out += `export type ${name} = ${type(schema)};\n`;
const operations = [];
for (const [path, methods] of Object.entries(spec.paths)) for (const [method, op] of Object.entries(methods)) {
  if (!['get', 'post', 'put', 'delete', 'patch'].includes(method)) continue;
  const responses = Object.entries(op.responses).filter(([status]) => /^2\d\d$/.test(status));
  if (!responses.length) throw new Error(`Missing success response: ${method} ${path}`);
  const params = op.parameters || [];
  const pathType = `{ ${params.filter(p => p.in === 'path').map(p => `${JSON.stringify(p.name)}: ${type(p.schema)}`).join('; ')} }`;
  const queryType = `{ ${params.filter(p => p.in === 'query').map(p => `${JSON.stringify(p.name)}${p.required ? '' : '?'}: ${type(p.schema)}`).join('; ')} }`;
  const body = content(op.requestBody);
  operations.push({ key: `${method.toUpperCase()} ${path}`, method: method.toUpperCase(), path,
    input: `{ path${pathType === '{  }' ? '?' : ''}: ${pathType}; query?: ${queryType}; body${body ? '' : '?'}: ${body ? type(body) : 'never'}; headers?: Record<string, string>; signal?: AbortSignal }`,
    output: responses.map(([, r]) => content(r) ? type(content(r)) : 'void').join(' | ') });
}
out += '\nexport interface Operations {\n' + operations.map(o => `  ${JSON.stringify(o.key)}: { input: ${o.input}; output: ${o.output} };`).join('\n') + '\n}\n';
out += 'export const endpoints = ' + JSON.stringify(Object.fromEntries(operations.map(o => [o.key, { method: o.method, path: o.path }])), null, 2) + ' as const;\n';
await writeFile('frontend/src/api/generated.ts', out);
